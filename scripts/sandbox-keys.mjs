// Creates sandbox/.rest-keys.env (git-ignored) with random secrets for the
// LOCAL sandbox, if missing. sandbox/seed.php registers them in WordPress on
// every boot, so they stay stable across restarts and are copied into
// .env.local once:
//   WOOCOMMERCE_CONSUMER_KEY / _SECRET  — WooCommerce REST v3 key
//   WORDPRESS_AUTH_SECRET               — signs storefront → WordPress auth calls
import { randomBytes } from "node:crypto";
import { appendFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";

const file = new URL("../sandbox/.rest-keys.env", import.meta.url);
const hex = (n = 20) => randomBytes(n).toString("hex");

if (!existsSync(file)) {
  writeFileSync(
    file,
    "# Local sandbox only (generated by scripts/sandbox-keys.mjs). Copy into .env.local.\n" +
      `WOOCOMMERCE_CONSUMER_KEY=ck_${hex()}\nWOOCOMMERCE_CONSUMER_SECRET=cs_${hex()}\nWORDPRESS_AUTH_SECRET=${hex(32)}\n`,
  );
  console.log("Created sandbox/.rest-keys.env — copy its values into .env.local.");
} else if (!readFileSync(file, "utf8").includes("WORDPRESS_AUTH_SECRET=")) {
  appendFileSync(file, `WORDPRESS_AUTH_SECRET=${hex(32)}\n`);
  console.log("Added WORDPRESS_AUTH_SECRET to sandbox/.rest-keys.env — copy it into .env.local.");
}
