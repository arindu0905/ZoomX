// Creates sandbox/.rest-keys.env (git-ignored) with random WooCommerce REST
// keys for the LOCAL sandbox, if it doesn't exist yet. sandbox/seed.php
// registers these keys in WooCommerce on every boot, so they stay stable
// across restarts and can be copied into .env.local once.
import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";

const file = new URL("../sandbox/.rest-keys.env", import.meta.url);
if (existsSync(file)) process.exit(0);
const hex = () => randomBytes(20).toString("hex");
writeFileSync(
  file,
  `# Local sandbox only (generated by scripts/sandbox-keys.mjs). Copy into .env.local.\nWOOCOMMERCE_CONSUMER_KEY=ck_${hex()}\nWOOCOMMERCE_CONSUMER_SECRET=cs_${hex()}\n`,
);
console.log("Created sandbox/.rest-keys.env — copy both values into .env.local.");
